import { test } from 'node:test';
import assert from 'node:assert/strict';
import { Pool } from 'pg';
import { migrate } from '../../scripts/migrate';
import { approvedUser } from '../../apps/web/lib/access';
import { makeSignature } from 'better-auth/crypto';
import { getMigrations } from 'better-auth/db/migration';
import { auth } from '../../apps/web/lib/auth';
import { db } from '../../apps/web/lib/db';
test('slice 0 PostgreSQL schema, auth lifecycle, constraints and restricted runtime', async () => {
 const admin = new Pool({ connectionString: process.env.MIGRATION_DATABASE_URL });
 try {
  await migrate(admin);
  await migrate(admin);
  const schema = await getMigrations(auth.options);
  assert.equal(schema.toBeCreated.length, 0);
  assert.equal(schema.toBeAdded.length, 0);
  const email = `slice0-${Date.now()}@example.com`;
  assert.equal(await approvedUser(db, email, true), null);
  await assert.rejects(auth.options.databaseHooks!.user!.create!.before!({ email, emailVerified: true } as never));
  await admin.query("INSERT INTO monitor.app_users(email,role,state) VALUES($1,'viewer','invited')", [email]);
  assert.equal(await approvedUser(db, email, true), null);
  await assert.rejects(admin.query("UPDATE monitor.app_users SET state='active' WHERE email=$1", [email]), { code: '23514' });
  await admin.query("UPDATE monitor.app_users SET state='active',approved_at=now() WHERE email=$1", [email]);
  assert.equal((await approvedUser(db, email, true))?.role, 'viewer');
  assert.equal(await approvedUser(db, email, false), null);
  await auth.options.databaseHooks!.user!.create!.before!({ email, emailVerified: true } as never);
  const ctx = await auth.$context;
  const user = await ctx.internalAdapter.createUser({ email, emailVerified: true, name: 'Slice 0 test' }, { method: 'oauth', oauth: { providerId: 'google', profile: {} } });
  const account = await ctx.internalAdapter.createAccount({ userId: user.id, providerId: 'google', accountId: user.id, accessToken: 'must-not-persist', refreshToken: 'must-not-persist', idToken: 'must-not-persist' });
  assert.equal(account.accessToken, null);
  const session = await ctx.internalAdapter.createSession(user.id);
  assert.ok(session);
  const signature = await makeSignature(session.token, process.env.BETTER_AUTH_SECRET!);
  const cookie = `${ctx.authCookies.sessionToken.name}=${encodeURIComponent(session.token + '.' + signature)}`;
  const signedSession = await auth.api.getSession({ headers: new Headers({ cookie }) });
  assert.equal(signedSession?.user.id, user.id);
  await assert.rejects(admin.query("INSERT INTO monitor.app_users(email) VALUES($1)", [email]), { code: '23505' });
  assert.equal((await ctx.internalAdapter.findSession(session.token))?.user.id, user.id);
  await admin.query("UPDATE monitor.app_users SET state='disabled' WHERE email=$1", [email]);
  assert.equal(await approvedUser(db, email, true), null);
  await assert.rejects(ctx.internalAdapter.createSession(user.id));
  await admin.query('DELETE FROM monitor.session WHERE "userId"=$1', [user.id]);
  assert.equal(await ctx.internalAdapter.findSession(session.token), null);
  assert.equal(await auth.api.getSession({ headers: new Headers({ cookie }) }), null);
  await assert.rejects(db.query('CREATE TABLE monitor.forbidden(id int)'), { code: '42501' });
  await assert.rejects(db.query("UPDATE monitor.app_users SET role='admin' WHERE email=$1", [email]), { code: '42501' });
  await assert.rejects(admin.query(`INSERT INTO monitor.session(id,"userId",token,"expiresAt") VALUES('orphan','missing','orphan',now()+interval '1 day')`), { code: '23503' });
  await assert.rejects(admin.query("UPDATE monitor.app_users SET role='owner' WHERE email=$1", [email]), { code: '23514' });
  await admin.query('DELETE FROM monitor."user" WHERE id=$1', [user.id]);
  await admin.query('DELETE FROM monitor.app_users WHERE email=$1', [email]);
 } finally { await admin.end(); await db.end(); }
});
